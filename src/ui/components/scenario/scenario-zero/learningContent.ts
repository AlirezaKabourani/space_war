import type { ScenarioDefinition, ScenarioNode } from "../../../../core/types/scenario";

export const getLearningPath = (scenario: ScenarioDefinition): string[] => {
  const path: string[] = [];
  let nodeId: string | undefined = scenario.start;
  while (nodeId && !path.includes(nodeId)) {
    const node: ScenarioNode | undefined = scenario.nodes[nodeId];
    if (!node) break;
    path.push(nodeId);
    if (node.type === "end") break;
    nodeId = "next" in node ? node.next : "options" in node ? node.options[0]?.next : undefined;
  }
  return path;
};

