export const buildReadingSections = (text: string, nodeId: string): ReadingSection[] => {
  const sections: ReadingSection[] = [];
  const paragraphs = text.split(/\n\s*\n/).filter((paragraph) => paragraph.trim());
  if (nodeId === "warGameExample" || nodeId === "gameTheoryExample") {
    return paragraphs.map((paragraph, index) => ({
      title: readingHeadings[nodeId]?.[index] ?? "شرح مسئله",
      text: paragraph.trim(),
    }));
  }
  paragraphs.forEach((paragraph, paragraphIndex) => {
    const sentences = paragraph.trim().split(/(?<=[.!؟؛])\s+/u);
    let current = "";
    let part = 0;
    const append = () => {
      if (!current) return;
      const heading = readingHeadings[nodeId]?.[paragraphIndex] ?? "دربارهٔ این مسیر آموزشی";
      sections.push({ title: `${heading}${part > 0 ? "؛ ادامه" : ""}`, text: current });
      current = "";
      part += 1;
    };
    for (const sentence of sentences) {
      if (current && current.length + sentence.length > 430) append();
      current = current ? `${current} ${sentence}` : sentence;
    }
    append();
  });
  return sections;
};

